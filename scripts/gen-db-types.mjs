// Generates src/api/databaseTypes.ts from the DEPLOYED Supabase database
// (the source of truth — not the DBML in docs/).
//
//   npx supabase login            (once; opens the browser for an access token)
//   npm run gen:types
//
// The project ref comes from SUPABASE_PROJECT_ID in the environment or in
// .env.local. Read-only: this only reads the schema.
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

function fromEnvFile(name) {
  if (!existsSync('.env.local')) return undefined
  const line = readFileSync('.env.local', 'utf8')
    .split(/\r?\n/)
    .find((entry) => entry.trim().startsWith(`${name}=`))
  return line?.slice(line.indexOf('=') + 1).trim() || undefined
}

const projectId = process.env.SUPABASE_PROJECT_ID || fromEnvFile('SUPABASE_PROJECT_ID')
if (!projectId) {
  console.error('Set SUPABASE_PROJECT_ID (the project ref) in .env.local or the environment.')
  process.exit(1)
}

const result = spawnSync('npx', ['supabase', 'gen', 'types', 'typescript', '--project-id', projectId, '--schema', 'public'], {
  encoding: 'utf8',
  shell: process.platform === 'win32',
})
if (result.status !== 0 || !result.stdout.trim()) {
  console.error(result.stderr || 'supabase gen types failed. Run `npx supabase login` first.')
  process.exit(result.status || 1)
}

const header = '// Generated by `npm run gen:types` from the deployed Supabase schema. Do not edit by hand.\n'
writeFileSync('src/api/databaseTypes.ts', header + result.stdout)
console.log('Wrote src/api/databaseTypes.ts')
